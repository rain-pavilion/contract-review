def verify() -> None:
    from docx import Document
    from docx.table import Table
    from docx.text.paragraph import Paragraph

    doc = Document(str(OUT_DOCX))
    body = doc.element.body

    # 1) 样式名自检
    used = {p.style.name for p in doc.paragraphs if p.text.strip()}
    bad_styles = sorted(s for s in used if s not in ALLOWED_STYLES)
    assert not bad_styles, f"样式名越界：{bad_styles}"

    # 2) 顺序遍历：图题在下、表题在上
    elements = [c for c in body.iterchildren() if c.tag.split("}")[-1] in ("p", "tbl")]
    order: list[tuple[str, str]] = []
    for child in elements:
        tag = child.tag.split("}")[-1]
        if tag == "p":
            para = Paragraph(child, doc)
            order.append(("p", para.style.name + "|" + para.text.strip()))
        else:
            order.append(("tbl", ""))

    fig_captions, tab_captions = 0, 0
    problems: list[str] = []
    for idx, (kind, payload) in enumerate(order):
        if kind != "p":
            continue
        style, text = payload.split("|", 1)
        if style != "Caption":
            continue
        if text.startswith("图"):
            fig_captions += 1
            if idx == 0 or "graphicData" not in elements[idx - 1].xml:
                problems.append(f"图题上方无图形对象：{text}")
        elif text.startswith("表"):
            tab_captions += 1
            if idx + 1 >= len(order) or order[idx + 1][0] != "tbl":
                problems.append(f"表题下方不是表格：{text}")
    assert not problems, "；".join(problems)

    # 3) 导出正文纯文本
    lines: list[str] = []
    for child in body.iterchildren():
        tag = child.tag.split("}")[-1]
        if tag == "p":
            para = Paragraph(child, doc)
            text = para.text.rstrip()
            if text:
                lines.append(text)
        elif tag == "tbl":
            table = Table(child, doc)
            for row in table.rows:
                cells = [c.text.strip().replace("\n", " ") for c in row.cells]
                lines.append(" | ".join(cells))
    text = "\n".join(lines) + "\n"
    OUT_TXT.write_text(text, encoding="utf-8")

    # 4) 参考文献编号连续
    ref_heading = text.rindex("参考文献")
    ref_block = text[ref_heading:]
    ref_nums = [int(m) for m in re.findall(r"^\[(\d+)\] ", ref_block, flags=re.M)]
    assert ref_nums == list(range(1, len(REFS) + 1)), "参考文献编号不连续"

    # 5) 正文引用的上界
    cites = [int(m) for m in re.findall(r"\[(\d+)\]", text[:ref_heading])]
    assert cites and max(cites) <= len(REFS), f"引用越界：max={max(cites)} 但仅有 {len(REFS)} 条文献"

    cjk = CJK_COUNT(text)
    para_count = sum(1 for line in lines if not line.startswith("|"))
    summary = {
        "file": str(OUT_DOCX),
        "size_bytes": OUT_DOCX.stat().st_size,
        "paragraphs": para_count,
        "cjk_chars": cjk,
        "refs": len(REFS),
        "citations": len(cites),
        "tables": len(doc.tables),
        "figures": fig_captions,
        "fig_captions": fig_captions,
        "tab_captions": tab_captions,
        "txt_bytes": OUT_TXT.stat().st_size,
        "distinct_cited_refs": len(set(cites)),
    }
    print("[summary] " + json.dumps(summary, ensure_ascii=False))
    print("[ok] 总段数 {paragraphs}、总汉字数 {cjk_chars}、参考文献 {refs} 条、"
          "正文引用 {citations} 处、表格 {tables} 张、插图 {figures} 幅".format(**summary))


if __name__ == "__main__":
    build()
