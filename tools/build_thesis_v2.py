PAGE_CHARS = 760          # 12pt 宋体、1.5 倍行距、A4 的每页汉字容量（经验值）
TABLE_COST = 260          # 表格折算的字符当量
FIGURE_COST = 620         # 插图折算的字符当量


def estimate_pages() -> dict[str, str]:
    """按字符当量估算每个标题所在的页码，供静态目录占位使用。"""
    pages: dict[str, str] = {"摘要": "I", "Abstract": "II"}
    budget = 0
    for name, args, kw in OPS:
        if name in ("h1", "h2", "h3"):
            pages.setdefault(args[0], str(1 + budget // PAGE_CHARS))
            continue
        if name == "refs":
            pages.setdefault("参考文献", str(1 + budget // PAGE_CHARS))
            budget += 26 * len(args[0])
        elif name == "ack":
            pages.setdefault("致谢", str(1 + budget // PAGE_CHARS))
            budget += len(args[0])
        elif name == "body":
            budget += len(args[0])
        elif name == "table":
            budget += TABLE_COST + sum(len(str(c)) for row in args[1] for c in row) // 3
        elif name == "figure":
            budget += FIGURE_COST
        elif name == "code_block":
            budget += 10 * args[0].count("\n")
    return pages


