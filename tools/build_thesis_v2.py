H1("第2章  关键技术简介")
H2("2.1  版面感知的文档结构化与 OCR")
P("电子文档在版面上并不等价于线性文本。一份排版规范的合同通常包含页眉页脚、双栏或三栏的签署页、跨页的表格以及带编号的多级标题，直接按段落顺序抽取，会把页眉标题混进条款正文，也会把跨页断裂的句子拆成两条。版面感知的解析思路是三步：先由字符或文本块的位置坐标恢复阅读顺序，再依据字号、加粗、编号形式与行距等视觉线索判定块的版面角色，最后按角色把块合成为逻辑段落。文献[13]把文本、布局与图像纳入统一掩码目标，文献[14]省去识别环节由图像直接生成结构化序列，文献[16]则把版面检测、表格与公式识别组织成流水线。这些工作共同的结论是：版面角色判定应当在字符识别之后、语义理解之前完成。顺序颠倒，后续的语义模型就无法区分标题与正文。对于扫描件，文字层缺失，必须引入光学字符识别。文献[15]的 PP-OCR 以轻量检测网络、方向分类器与蒸馏识别网络实现中文场景的可部署识别，其精度与速度的折中适合中央处理器推理。")
P("本文系统在解析层把文件分为三类：带文字层的电子文档、纯图像页与混合文档。电子文档走坐标投影与角色判定；图像页进入识别通道，输出带置信度的字符序列与检测框；混合文档按页判定，逐页决定通道。识别结果统一封装为 SourceBlock，记录页码、外接框、版面角色、文本内容与识别置信度。")
P("后续环节只依赖这一结构，从而把“用哪种解析器”与“怎么审查”解耦。解析层的改动不再牵动审查规则。识别通道设置了页数与时间两项预算。超预算的页面标记为跳过并写入降级记录，避免一份两百页的扫描合同把整个审查流程拖死，实测在中央处理器、200 dpi 条件下，单页识别以秒计，中位与最慢页的差距在一倍以内，平均置信度接近一。以带文字层的页面为参照计算字符错误率，池化值不到百分之一。这一精度足以支撑条款边界与要素抽取，但识别仍是全流程最慢的环节，系统因此按文件指纹缓存识别结果，同一份合同重复审查不再重跑识别。")

H2("2.2  多智能体协同与图结构引导")
P("多智能体协同的基本假设是：把复杂任务拆成职责单一的子任务，由不同执行体分别完成并相互校核，整体表现可以优于单体执行。文献[24]把协作抽象为可编排的消息传递与会话状态，文献[25]把标准作业程序编码为提示序列并用结构化产物约束交接，文献[26]让执行体把失败轨迹写入情节记忆以修正后续行为，文献[27]则通过多个执行体的辩论提升事实性。这些机制的有效性依赖两个前提：子任务之间确实可以解耦，以及存在可靠的收敛判据。缺少收敛判据时，多轮互相批评容易退化为互相附和的空转。本文系统据此把审查拆为五个智能体。理解智能体负责把条款与要素组织成待审查的任务清单；条款审查智能体在单条款范围内按风险码逐项判定；交叉审查智能体沿条款引用与义务链检查跨条款矛盾，例如付款节点与交付节点倒置、违约金比例与合同总价不匹配。法条检索智能体为每条待定风险寻找支撑条文；裁量智能体在证据强度不足时给出保留意见并推入人工复核队列。五个智能体由自研的有向无环图引擎调度，支持并行分支与节点级轨迹记录。")
P("为抑制无效迭代，引擎设置了证据、引用、裁量与仲裁四路有界回环，每路最多触发一次，触发条件与次数都写入轨迹，使“反思”成为可计数的控制流，而不是提示词里的模糊要求。")
