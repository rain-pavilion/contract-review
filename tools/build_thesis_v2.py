H2("3.1  系统目标")
P("系统的总体目标是：在普通办公计算机上，把一份中文政府采购合同从原始文件转换为可复核的审查报告，报告中的每一条风险都能追溯到具体条款与具体法条，且整个转换过程不依赖外部大模型服务。这一目标可以分解为三个可度量的子目标。其一是覆盖度，报告需要覆盖权属、价款、履约、违约救济与程序性材料五个方面的常见缺陷，并以固定的风险码体系表达，使不同合同之间可以横向比较，其二是可溯源性，任何风险条目的引用必须存在于本地法条库，禁止由模型自由生成条文号；证据不足时系统只给出保留意见，不做外推。其三是时效性，单份合同的审查应在数秒内完成，使批量筛查成为可能。三个子目标之间存在张力。提高覆盖度往往意味着引入更多判定规则与更多候选引用，这会推高误报率并拉长耗时；强化可溯源性要求引用只能来自本地库，限制了表达自由度；追求时效性则排斥大参数量模型与复杂推理链。")
P("系统分析的实质就是在这三者的可行域内确定取舍：把判定交给确定性规则，把排序与置信度交给轻量学习组件，把难以判定的情形推入人工复核队列，用“机器初筛、人工定案”的分工，替代“机器自动出结论”的设想。后者听起来更彻底，实际做不出来。")

