def grab_code(path: Path, start_marker: str, count: int,
              tail_marker: str | None = None) -> str:
    """按标记从真实源码里截取行，保证附录代码与仓库一致。"""
    lines = path.read_text(encoding="utf-8").splitlines()
    begin = next(i for i, line in enumerate(lines) if start_marker in line)
    chunk = lines[begin:begin + count]
    if tail_marker is not None:
        end = next(i for i, line in enumerate(chunk) if tail_marker in line)
        chunk = chunk[:end + 1]
    return "\n".join(chunk)


