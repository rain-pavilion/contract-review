H2("5.1  文档解析与版面还原")
P("解析模块按扩展名分派到四个解析器，分别处理文字型文档、可移植文档、纯文本与网页；图像文件直接进入识别通道。文字型文档的解析分两步：先读取段落与表格，再对每个段落按字符位置计算行内空隙，用于恢复被制表符打散的签署栏，可移植文档优先读取文字层，按字符坐标做行聚类，行内按横坐标排序，行间按纵坐标排序，从而得到阅读顺序。分栏识别用投影法：把页面按横坐标切成细柱，统计每柱的字符覆盖，长期为空的柱被认定为栏间空白，据此把页面切成左右栏并分别排序。这一手法简单，但对通栏标题不敏感——标题所在的行会被判成栏间空白，所以判栏前要先剔除跨栏行。页眉页脚剥离依据两个信号：位置与重复。落在页面顶部或底部百分之八区域内的文本行先被标记为候选，若同一文本在多页的相同相对位置重复出现，则判定为页眉页脚并从正文流中移除。只出现一次的候选保留，避免误删首页的标题行。")
