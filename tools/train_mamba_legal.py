"""Train an isolated BERT-Mamba checkpoint on hash-pinned released legal labels.

Requires a verified source manifest. No labels are generated by this script.
Auxiliary statute-conflict results are never contract-law benchmark scores.
Existing checkpoints and the serving process are never modified or restarted.
"""
from __future__ import annotations

import argparse
from collections import Counter
from datetime import datetime, timezone
import gc
import hashlib
import json
import math
import os
from pathlib import Path
import random
import sys
import time

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
os.environ.setdefault('HF_HUB_OFFLINE', '1')
os.environ.setdefault('TRANSFORMERS_OFFLINE', '1')
os.environ.setdefault('OMP_NUM_THREADS', '2')

from legal_training_data import prepare, sha256


def file_hash(path):
    result=hashlib.sha256()
    with Path(path).open('rb') as source:
        for chunk in iter(lambda:source.read(4*1024*1024),b''):
            result.update(chunk)
    return result.hexdigest()


def tensor_hash(state):
    result=hashlib.sha256()
    for name,value in sorted(state.items()):
        result.update(name.encode())
        result.update(value.detach().cpu().contiguous().numpy().tobytes())
    return result.hexdigest()


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--manifest', type=Path, required=True)
    p.add_argument('--output', type=Path, default=ROOT/'zhilv_qiling_v2/models/bert_mamba_legal_20261115')
    p.add_argument('--evidence', type=Path, default=ROOT/'tools/acceptance_results/real_legal_training_20261115')
    p.add_argument('--init', type=Path, default=ROOT/'zhilv_qiling_v2/models/bert_mamba_entail')
    p.add_argument('--epochs', type=int, default=3)
    p.add_argument('--batch-size', type=int, default=4)
    p.add_argument('--max-length', type=int, default=128)
    p.add_argument('--train-cap', type=int, default=1200)
    p.add_argument('--valid-cap', type=int, default=128)
    p.add_argument('--test-cap', type=int, default=128)
    p.add_argument('--seed', type=int, default=20261115)
    p.add_argument('--lr', type=float, default=3e-5)
    p.add_argument('--gpu-memory-fraction', type=float, default=.24)
    p.add_argument('--prepare-only', action='store_true')
    args = p.parse_args()
    if args.epochs < 1 or args.batch_size < 1 or args.max_length < 16:
        p.error('positive training budgets are required')
    if not 0 < args.gpu_memory_fraction <= .26:
        p.error('GPU allocator fraction must be in (0,.26]')
    if args.output.exists() and any(args.output.iterdir()):
        p.error('refuse to overwrite an existing checkpoint directory')
    if args.evidence.exists() and any(args.evidence.iterdir()):
        p.error('refuse to overwrite an existing evidence directory')
    args.evidence.mkdir(parents=True, exist_ok=True)
    receipt = {'status':'initializing', 'started_at_utc':datetime.now(timezone.utc).isoformat(),
        'command':sys.argv, 'seed':args.seed, 'product_default_replaced':False,
        'project_human_gold':False, 'official_benchmark_score':False,
        'training_labels_generated':False, 'cpu_threads':2, 'cpu_interop_threads':1,
        'implementation_sha256':{name:sha256((ROOT/name).read_bytes()) for name in
            ('tools/train_mamba_legal.py','tools/legal_training_data.py','tools/legal_training_lcr_cn.py',
             'zhilv_qiling_v2/bert_entail.py')}}
    started = time.perf_counter()
    def save():
        (args.evidence/'run.json').write_text(json.dumps(receipt, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    torch = None
    try:
        data = prepare(args.manifest, seed=args.seed, caps={'train':args.train_cap, 'valid':args.valid_cap, 'test':args.test_cap})
        receipt['source'] = {key:value for key,value in data.items() if key != 'splits'}
        receipt['task'] = data['manifest']['task']
        receipt['supervision'] = 'original_released_legal_labels_auxiliary_task_not_project_human_gold'
        receipt['training_scope'] = 'auxiliary_original_conflict_type_classification_not_contract_law_entailment_acceptance'
        labels = sorted(set(data['manifest']['label_mapping'].values()))
        label2id = {label:index for index,label in enumerate(labels)}
        receipt['class_names'] = labels
        receipt['compatible_with_contract_entailment_runtime'] = False
        canonical = '\n'.join(json.dumps({'derived_split':split, **row}, ensure_ascii=False, sort_keys=True)
            for split, rows in data['splits'].items() for row in rows) + '\n'
        (args.evidence/'pairs.jsonl').write_text(canonical, encoding='utf-8')
        receipt['prepared_pairs_sha256'] = sha256(canonical)
        receipt['status'] = 'original_labels_prepared'
        save()
        if args.prepare_only:
            return 0
        import torch
        from transformers import AutoTokenizer
        from zhilv_qiling_v2 import bert_entail as B
        torch.set_num_threads(2)
        torch.set_num_interop_threads(1)
        if not torch.cuda.is_available():
            raise RuntimeError('CUDA budget required; refusing to compete with the CPU 8B process')
        free,total = torch.cuda.mem_get_info()
        if free < 2500*1024**2:
            raise RuntimeError('less than 2500 MiB free GPU memory; no applications will be closed')
        torch.cuda.set_per_process_memory_fraction(args.gpu_memory_fraction)
        torch.cuda.reset_peak_memory_stats()
        random.seed(args.seed)
        torch.manual_seed(args.seed)
        torch.cuda.manual_seed_all(args.seed)
        torch.backends.cudnn.benchmark = False
        torch.backends.cudnn.deterministic = True
        device = torch.device('cuda')
        receipt['resources'] = {'torch':torch.__version__, 'cuda':torch.version.cuda,
            'gpu':torch.cuda.get_device_name(), 'free_gpu_before_bytes':free, 'total_gpu_bytes':total,
            'allocator_fraction_limit':args.gpu_memory_fraction, 'no_user_applications_closed':True}
        initial_meta = json.loads((args.init/'meta.json').read_text(encoding='utf-8'))
        architecture = initial_meta['architecture']
        if not architecture.get('mamba') or architecture.get('rule_residual'):
            raise ValueError('explicit existing Mamba checkpoint without rule residual required')
        init_hash = file_hash(args.init/'model.pt')
        receipt['initial_checkpoint'] = {'path':str(args.init), 'sha256':init_hash}
        tokenizer = AutoTokenizer.from_pretrained(str(args.init), local_files_only=True)
        model = B.build_model(enable_mamba=True, enable_rule_head=False,
            mamba_config=architecture['mamba_config'], dropout=.1)
        model.load_state_dict(torch.load(args.init/'model.pt', map_location='cpu', weights_only=True), strict=True)
        # Released conflict-type classes are not entail/contradict/neutral.
        # A separate head deliberately prevents presenting this auxiliary model
        # as a trained contract-law entailment classifier.
        model.head[-1] = torch.nn.Linear(model.head[-1].in_features, len(labels))
        receipt['baseline_scope'] = 'Same initialization and same fixed held-out rows before/after training; native conflict-type output head freshly initialized; not a zero-shot official model score.'
        model.encoder.requires_grad_(False)
        model.mamba.embeddings.requires_grad_(False)
        receipt['frozen'] = ['encoder', 'mamba.embeddings_unused']
        receipt['trainable'] = ['mamba_state_space', 'mamba_projections', 'pool_gate', 'cross_attention', 'norm', 'classification_head']
        # Do not silently truncate source laws. The selected subset and rejected
        # long rows remain independently auditable, with original IDs preserved.
        splits, too_long = {}, []
        for split, rows in data['splits'].items():
            splits[split] = []
            for row in rows:
                lengths = [len(tokenizer(row[field], truncation=False)['input_ids']) for field in ('clause','article')]
                if max(lengths) > args.max_length:
                    too_long.append({'pair_id':row['pair_id'], 'split':split, 'token_lengths':lengths})
                else:
                    splits[split].append(row)
        if any(set(r['label'] for r in rows) != set(labels) for rows in splits.values()):
            raise ValueError('sequence budget filtering removed a released target class or split; increase explicit budget')
        receipt['sequence_budget'] = {'max_tokens_each_tower':args.max_length, 'truncation':False,
            'excluded_long_rows':too_long, 'actual_counts':{k:dict(Counter(row['label'] for row in v)) for k,v in splits.items()}}
        (args.evidence/'used_pairs.jsonl').write_text('\n'.join(json.dumps({'derived_split':s,**row},ensure_ascii=False,sort_keys=True)
            for s,rows in splits.items() for row in rows)+'\n',encoding='utf-8')
        model.to(device)
        receipt['architecture'] = {**architecture, 'dropout':.1, 'frozen':receipt['frozen'],
            'trainable_parameters':sum(p.numel() for p in model.parameters() if p.requires_grad),
            'all_parameters':sum(p.numel() for p in model.parameters())}
        def encode(rows):
            left = tokenizer([r['clause'] for r in rows],padding=True,truncation=False,return_tensors='pt')
            right = tokenizer([r['article'] for r in rows],padding=True,truncation=False,return_tensors='pt')
            targets = torch.tensor([label2id[r['label']] for r in rows],device=device)
            return left,right,targets
        def evaluate(rows):
            model.eval()
            confusion = {label:{other:0 for other in labels} for label in labels}
            predictions = []
            with torch.no_grad():
                for offset in range(0,len(rows),args.batch_size):
                    batch = rows[offset:offset+args.batch_size]
                    c,a,y = encode(batch)
                    logits,_,_ = model(c['input_ids'].to(device),c['attention_mask'].to(device),a['input_ids'].to(device),a['attention_mask'].to(device))
                    for row,index in zip(batch,logits.argmax(dim=1).tolist()):
                        pred = labels[index]
                        confusion[row['label']][pred] += 1
                        predictions.append({'pair_id':row['pair_id'],'original_id':row['original_id'],'expected':row['label'],'predicted':pred})
            f1s = []
            for label in labels:
                tp=confusion[label][label]
                fp=sum(confusion[other][label] for other in labels if other!=label)
                fn=sum(confusion[label][other] for other in labels if other!=label)
                f1s.append(2*tp/(2*tp+fp+fn) if 2*tp+fp+fn else 0.)
            return {'rows':len(rows),'supported_target_labels':labels,'macro_f1_supported_labels':sum(f1s)/len(f1s),
                'accuracy':sum(confusion[label][label] for label in labels)/len(rows),
                'confusion':confusion,'predictions':predictions,
                'scope':receipt['training_scope']}
        receipt['before_valid'] = evaluate(splits['valid'])
        receipt['before_test'] = evaluate(splits['test'])
        before = {n:p.detach().cpu().clone() for n,p in model.named_parameters() if p.requires_grad}
        receipt['mamba_core_sha256_before'] = tensor_hash({n:p for n,p in before.items() if n.startswith('mamba.')})
        params = [p for p in model.parameters() if p.requires_grad]
        optimizer = torch.optim.AdamW(params,lr=args.lr,weight_decay=.01)
        counts=Counter(row['label'] for row in splits['train'])
        weights=torch.tensor([len(splits['train'])/(len(labels)*counts[label]) if counts[label] else 0. for label in labels],device=device)
        loss_fn=torch.nn.CrossEntropyLoss(weight=weights)
        generator=torch.Generator().manual_seed(args.seed)
        receipt.update(status='training',epochs=args.epochs,learning_rate=args.lr,batch_size=args.batch_size,
            completed_optimizer_steps=0,gradient_evidence={},history=[])
        save()
        for epoch in range(1,args.epochs+1):
            model.train()
            model.encoder.eval()
            order=torch.randperm(len(splits['train']),generator=generator).tolist()
            losses=[]
            for offset in range(0,len(order),args.batch_size):
                batch=[splits['train'][i] for i in order[offset:offset+args.batch_size]]
                c,a,y=encode(batch)
                optimizer.zero_grad(set_to_none=True)
                logits,_,_=model(c['input_ids'].to(device),c['attention_mask'].to(device),a['input_ids'].to(device),a['attention_mask'].to(device))
                loss=loss_fn(logits,y)
                if not torch.isfinite(loss): raise RuntimeError('non-finite training loss')
                loss.backward()
                for name,parameter in model.named_parameters():
                    if parameter.requires_grad and parameter.grad is not None:
                        norm=float(parameter.grad.detach().float().norm())
                        if not math.isfinite(norm): raise RuntimeError('non-finite gradient')
                        evidence=receipt['gradient_evidence'].setdefault(name,{'max_l2':0.,'nonzero_steps':0})
                        evidence['max_l2']=max(evidence['max_l2'],norm)
                        evidence['nonzero_steps']+=int(norm>0)
                torch.nn.utils.clip_grad_norm_(params,1.)
                optimizer.step()
                losses.append(float(loss.detach()))
                receipt['completed_optimizer_steps']+=1
                if receipt['completed_optimizer_steps']%50==0:
                    save()
                    print(f"epoch={epoch} step={receipt['completed_optimizer_steps']} loss={losses[-1]:.5f}",flush=True)
            receipt['history'].append({'epoch':epoch,'mean_cross_entropy':sum(losses)/len(losses)})
            save()
        receipt['after_valid']=evaluate(splits['valid'])
        receipt['after_test']=evaluate(splits['test'])
        after={n:p.detach().cpu().clone() for n,p in model.named_parameters() if n in before}
        receipt['mamba_core_sha256_after']=tensor_hash({n:p for n,p in after.items() if n.startswith('mamba.')})
        receipt['parameter_changes']={n:float((after[n]-value).float().norm()) for n,value in before.items()}
        if not any(value>0 and name.startswith('mamba.') and any(p in name for p in ('A_log','.D','x_proj','dt_proj'))
            for name,value in receipt['parameter_changes'].items()):
            raise RuntimeError('Mamba selective-state-space parameters did not change')
        if file_hash(args.init/'model.pt') != init_hash:
            raise RuntimeError('initial checkpoint was unexpectedly modified')
        args.output.mkdir(parents=True,exist_ok=True)
        (args.output/'.gitignore').write_text('*\n',encoding='ascii')
        torch.save({n:v.detach().cpu() for n,v in model.state_dict().items()},args.output/'model.pt')
        tokenizer.save_pretrained(str(args.output))
        meta={key:receipt[key] for key in ('architecture','supervision','training_scope','task')}
        meta.update(source_manifest_sha256=data['manifest_sha256'],training_evidence=str(args.evidence),
            human_gold=False,product_default_unchanged=True,contract_law_quality_accepted=False,
            auxiliary_legal_dataset=True,optimizer_steps=receipt['completed_optimizer_steps'],
            class_names=labels,num_labels=len(labels),compatible_with_contract_entailment_runtime=False,
            trained_at=datetime.now(timezone.utc).isoformat())
        (args.output/'meta.json').write_text(json.dumps(meta,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
        receipt['checkpoint']={'path':str(args.output/'model.pt'),'sha256':file_hash(args.output/'model.pt')}
        del optimizer,params,model,before,after,logits,loss,c,a,y,batch
        gc.collect()
        torch.cuda.empty_cache()
        os.environ['ZLQL_ENTAILMENT_DEVICE']='cuda'
        loaded=B.build_model(enable_mamba=True,enable_rule_head=False,
            mamba_config=architecture['mamba_config'],dropout=.1)
        loaded.head[-1]=torch.nn.Linear(loaded.head[-1].in_features,len(labels))
        loaded.load_state_dict(torch.load(args.output/'model.pt',map_location='cpu',weights_only=True),strict=True)
        loaded.to(device).eval()
        receipt['strict_reload']={'mamba':True,'strict_checkpoint_load':True,'num_labels':len(labels),
            'task':receipt['task'],'compatible_with_contract_entailment_runtime':False}
        receipt['reload_predictions']=[]
        with torch.no_grad():
            for row in splits['test'][:3]:
                c,a,_=encode([row])
                logits,cosine,_=loaded(c['input_ids'].to(device),c['attention_mask'].to(device),a['input_ids'].to(device),a['attention_mask'].to(device))
                probabilities=logits.softmax(dim=-1)[0]
                index=int(probabilities.argmax())
                receipt['reload_predictions'].append({'pair_id':row['pair_id'],'original_expected':row['label'],
                    'predicted_conflict_type':labels[index],'probabilities':{label:float(probabilities[i]) for i,label in enumerate(labels)},
                    'cosine':float(cosine[0])})
        expected_after = {row['pair_id']:row['predicted'] for row in receipt['after_test']['predictions']}
        if any(expected_after[row['pair_id']] != row['predicted_conflict_type'] for row in receipt['reload_predictions']):
            raise RuntimeError('strict-reloaded predictions differ from the saved trained model')
        receipt['strict_reload_predictions_match_after_test'] = True
        receipt.update(status='trained_strict_reloaded_predictions_completed',
            peak_cuda_allocated_bytes=torch.cuda.max_memory_allocated(),peak_cuda_reserved_bytes=torch.cuda.max_memory_reserved())
        del loaded
    except BaseException as exc:
        receipt.update(status='failed',error_type=type(exc).__name__,error=str(exc))
        raise
    finally:
        if torch is not None and torch.cuda.is_available():
            gc.collect()
            torch.cuda.empty_cache()
        receipt['finished_at_utc']=datetime.now(timezone.utc).isoformat()
        receipt['total_seconds']=time.perf_counter()-started
        save()
        print(json.dumps({'status':receipt['status'],'evidence':str(args.evidence/'run.json'),
            'steps':receipt.get('completed_optimizer_steps'),'error':receipt.get('error')},ensure_ascii=True),flush=True)
    return 0


if __name__=='__main__':
    raise SystemExit(main())
